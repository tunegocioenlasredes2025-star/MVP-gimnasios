function icon(name, size = 20) {
  return `<svg class="ic" width="${size}" height="${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round">${ICONS[name] || ""}</svg>`;
}

// Inyecta iconos en elementos con data-icon (sidebar estático, etc.).
function renderIcons(root = document) {
  root.querySelectorAll("[data-icon]").forEach((el) => {
    const size = el.getAttribute("data-icon-size") || 20;
    el.insertAdjacentHTML("afterbegin", icon(el.getAttribute("data-icon"), size));
    el.removeAttribute("data-icon");
  });
}
document.addEventListener("DOMContentLoaded", () => renderIcons());
